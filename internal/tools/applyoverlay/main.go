// Command applyoverlay applies an OpenAPI Overlay to a raw spec document and
// writes the result.
//
// oapi-codegen can apply overlays itself, but only after the spec has been
// parsed and validated. The pinned Iceberg spec does not validate as-is, so
// the overlay must be applied to the raw YAML first.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"

	"github.com/speakeasy-api/openapi/overlay/loader"
	"gopkg.in/yaml.v3"
)

const outputHeader = "# Code generated by applyoverlay. DO NOT EDIT.\n"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "applyoverlay:", err)
		os.Exit(1)
	}
}

func run() error {
	specPath := flag.String("spec", "", "path to the source OpenAPI spec")
	overlayPath := flag.String("overlay", "", "path to the OpenAPI Overlay document")
	outPath := flag.String("out", "", "path to write the patched spec to")
	flag.Parse()

	if *specPath == "" || *overlayPath == "" || *outPath == "" {
		return errors.New("-spec, -overlay and -out are required")
	}

	raw, err := os.ReadFile(*specPath)
	if err != nil {
		return fmt.Errorf("reading spec: %w", err)
	}

	var root yaml.Node
	if err = yaml.Unmarshal(raw, &root); err != nil {
		return fmt.Errorf("parsing spec %q: %w", *specPath, err)
	}

	ov, err := loader.LoadOverlay(*overlayPath)
	if err != nil {
		return fmt.Errorf("loading overlay: %w", err)
	}

	if err := ov.Validate(); err != nil {
		return fmt.Errorf("validating overlay %q: %w", *overlayPath, err)
	}

	// Strict mode fails when an action's target matches nothing, so a spec
	// update that makes a fix obsolete is noticed instead of silently ignored.
	if _, err := ov.ApplyToStrict(&root); err != nil {
		return fmt.Errorf("applying overlay: %w", err)
	}

	var buf bytes.Buffer
	buf.WriteString(outputHeader)

	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)

	if err := enc.Encode(&root); err != nil {
		return fmt.Errorf("encoding patched spec: %w", err)
	}

	if err := enc.Close(); err != nil {
		return fmt.Errorf("encoding patched spec: %w", err)
	}

	//nolint:gosec // G306: generated spec is committed to the repo, not a secret.
	if err := os.WriteFile(*outPath, buf.Bytes(), 0o644); err != nil {
		return fmt.Errorf("writing %q: %w", *outPath, err)
	}

	return nil
}
